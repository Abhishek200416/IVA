@dataclass
class OptionQuote:
    """Option strike quote representing market observations."""
    strike: float
    option_type: str  # "CE" or "PE"
    market_price: float
    bid: float
    ask: float
    implied_vol: float
    open_interest: int
    volume: int


@dataclass
class AlphaSignal:
    """Alpha signal generated by comparing market IV against arbitrage-free SVI smile."""
    signal_id: str
    underlying: str
    strike: float
    option_type: str
    spot_price: float
    market_iv: float
    svi_model_iv: float
    iv_discrepancy: float  # market_iv - svi_model_iv
    action: str  # "BUY" (underpriced) or "SELL" (overpriced)
    expected_edge_bps: float
    confidence_score: float
    timestamp: float = field(default_factory=time.time)


@dataclass
class AlphaCycleSummary:
    """Summary of a completed autonomous alpha and compounding cycle."""
    cycle_id: str
    underlying: str
    spot_price: float
    svi_parameters: Dict[str, float]
    signals_detected: int
