"""TradingAgents: Multi-Agent LLM Financial Trading & Dialectical Debate Framework.

Inspired by TauricResearch/TradingAgents (arXiv:2412.20138):
Implements a collaborative, role-based multi-agent consensus architecture for
Indian BANK NIFTY index options:

Roles:
1. BullishResearchAnalyst: Formulates bullish hypothesis from momentum, VWAP breakouts, and Call OI build-up.
2. BearishResearchAnalyst: Formulates bearish hypothesis from resistance levels, IV expansion, and Put unwinding.
3. PortfolioSynthesizer: Reconciles the Bull vs Bear debate, derives net conviction, and selects optimal option strategy
   (Directional Spread, Short Strangle, Iron Condor, or Cash Neutral).
4. RiskManagerAuditor: Validates proposed trade against pre-trade risk controls and drawdown limits.
5. DecisionAuditRecord: Provides complete, explainable audit trace of the consensus process.
"""

from __future__ import annotations

import dataclasses
import enum
from typing import Any, Dict, List, Optional


class StrategyType(enum.Enum):
    """Trading strategy classification."""

    LONG_CALL = "LONG_CALL"
    LONG_PUT = "LONG_PUT"
    BULL_CALL_SPREAD = "BULL_CALL_SPREAD"
    BEAR_PUT_SPREAD = "BEAR_PUT_SPREAD"
    SHORT_STRANGLE = "SHORT_STRANGLE"
    IRON_CONDOR = "IRON_CONDOR"
    NO_TRADE_NEUTRAL = "NO_TRADE_NEUTRAL"


@dataclasses.dataclass(frozen=True)
class AnalystReport:
    """Perspective report generated by a specialized analyst agent."""

    agent_role: str
    stance: str  # BULLISH, BEARISH, or NEUTRAL
    conviction: float  # 0.0 to 1.0
    thesis: str
    catalysts: list[str]


@dataclasses.dataclass(frozen=True)
class SynthesizedTradeDecision:
    """Final consensus decision derived from the multi-agent dialectical debate."""

    strategy: StrategyType
    net_conviction: float  # -1.0 (Extreme Bear) to +1.0 (Extreme Bull), ~0.0 is Rangebound
    confidence_score: float  # 0.0 to 1.0
    target_strikes: list[float]
    rationale: str
    risk_status: str  # APPROVED or REJECTED_BY_RMS
    debate_transcript: dict[str, Any]


class TradingAgentsDebateEngine:
    """Orchestrates dialectical debate between Bull and Bear agents for options selection."""

    CONVICTION_THRESHOLD: float = 0.35  # Minimum net conviction required for directional spread
    CHOP_VOL_FLOOR: float = 0.12        # Minimum IV for Short Strangle theta harvesting

    @classmethod
    def evaluate_bullish_analyst(
        cls,
        spot: float,
        vwap: float,
        ema20: float,
        call_oi_change_pct: float,
        put_oi_change_pct: float,
    ) -> AnalystReport:
        """Bullish Analyst analyzes upward momentum and Call-side support."""
        catalysts: list[str] = []
        score = 0.0

        if spot > vwap:
            score += 0.35
            catalysts.append(f"Spot ({spot:.1f}) trading above VWAP ({vwap:.1f})")
        if spot > ema20:
            score += 0.35
            catalysts.append(f"Spot trading above 20 EMA ({ema20:.1f})")
        if put_oi_change_pct > call_oi_change_pct:
            score += 0.30
            catalysts.append(f"Put writing OI (+{put_oi_change_pct:.1f}%) exceeds Call writing (+{call_oi_change_pct:.1f}%)")

        conviction = min(1.0, score)
        thesis = (
            f"Bullish momentum supported by VWAP/EMA alignment and strong Put base. Conviction: {conviction:.2f}"
            if conviction >= 0.5
            else "Weak or non-committal bullish indicators."
        )

        return AnalystReport(
            agent_role="BullishResearchAnalyst",
            stance="BULLISH" if conviction >= 0.5 else "NEUTRAL",
            conviction=conviction,
            thesis=thesis,
            catalysts=catalysts,
        )

    @classmethod
    def evaluate_bearish_analyst(
        cls,
        spot: float,
        vwap: float,
        ema20: float,
        iv: float,
        call_oi_change_pct: float,
        put_oi_change_pct: float,
    ) -> AnalystReport:
        """Bearish Analyst analyzes downward pressure, resistance, and IV spikes."""
        catalysts: list[str] = []
        score = 0.0

        if spot < vwap:
            score += 0.35
            catalysts.append(f"Spot ({spot:.1f}) below VWAP ({vwap:.1f}) indicating institutional selling")
        if spot < ema20:
            score += 0.35
            catalysts.append(f"Spot below 20 EMA ({ema20:.1f}) confirming short-term downtrend")
        if call_oi_change_pct > put_oi_change_pct:
            score += 0.30
            catalysts.append(f"Heavy Call writing OI (+{call_oi_change_pct:.1f}%) creating overhead resistance")

        conviction = min(1.0, score)
        thesis = (
            f"Bearish breakdown indicated by overhead supply and Call OI accumulation. Conviction: {conviction:.2f}"
            if conviction >= 0.5
            else "Weak bearish pressure; downside risks limited."
        )

        return AnalystReport(
            agent_role="BearishResearchAnalyst",
            stance="BEARISH" if conviction >= 0.5 else "NEUTRAL",
            conviction=conviction,
            thesis=thesis,
            catalysts=catalysts,
        )

    @classmethod
    def synthesize_debate_decision(
        cls,
        spot: float,
        bull_report: AnalystReport,
        bear_report: AnalystReport,
        iv: float,
        account_drawdown_pct: float = 0.0,
        max_drawdown_limit: float = 0.03,  # 3.0% RMS limit
    ) -> SynthesizedTradeDecision:
        """Synthesizes Bull vs Bear debate and applies RMS gating."""
        # Net conviction is Bull Conviction minus Bear Conviction in [-1.0, +1.0]
        net_conviction = bull_report.conviction - bear_report.conviction
        confidence = (bull_report.conviction + bear_report.conviction) / 2.0

        atm_strike = round(round(spot / 100.0) * 100.0)

        # 1. Check Pre-Trade Risk Management (RMS) Guardrail
        if account_drawdown_pct >= max_drawdown_limit:
            return SynthesizedTradeDecision(
                strategy=StrategyType.NO_TRADE_NEUTRAL,
                net_conviction=net_conviction,
                confidence_score=confidence,
                target_strikes=[],
                rationale=f"RMS CIRCUIT BREAKER: Account drawdown ({account_drawdown_pct * 100:.1f}%) exceeds {max_drawdown_limit * 100:.1f}% limit.",
                risk_status="REJECTED_BY_RMS",
                debate_transcript={
                    "bull_report": dataclasses.asdict(bull_report),
                    "bear_report": dataclasses.asdict(bear_report),
                    "rms_override": True,
                },
            )

        # 2. Strategy Synthesis
        if net_conviction >= cls.CONVICTION_THRESHOLD:
            # Strong Bullish -> Bull Call Spread (ATM Long Call, OTM +300 Short Call)
            strategy = StrategyType.BULL_CALL_SPREAD
            target_strikes = [atm_strike, atm_strike + 300.0]
            rationale = (
                f"BULL CONSENSUS: Bull conviction ({bull_report.conviction:.2f}) dominant. "
                f"Selected Bull Call Spread [{target_strikes[0]}/{target_strikes[1]}]."
            )
        elif net_conviction <= -cls.CONVICTION_THRESHOLD:
            # Strong Bearish -> Bear Put Spread (ATM Long Put, OTM -300 Short Put)
            strategy = StrategyType.BEAR_PUT_SPREAD
            target_strikes = [atm_strike, atm_strike - 300.0]
            rationale = (
                f"BEAR CONSENSUS: Bear conviction ({bear_report.conviction:.2f}) dominant. "
                f"Selected Bear Put Spread [{target_strikes[0]}/{target_strikes[1]}]."
            )
        else:
            # Balanced / Neutral Market -> Non-Directional Theta Harvest
            if iv >= cls.CHOP_VOL_FLOOR:
                strategy = StrategyType.SHORT_STRANGLE
                target_strikes = [atm_strike - 400.0, atm_strike + 400.0]  # OTM PE / OTM CE
                rationale = (
                    f"SIDEWAYS CONSENSUS: Balanced debate (net conviction {net_conviction:.2f}). "
                    f"Selected Short Strangle [{target_strikes[0]} PE / {target_strikes[1]} CE] for theta collection."
                )
            else:
                strategy = StrategyType.NO_TRADE_NEUTRAL
                target_strikes = []
                rationale = (
                    f"NEUTRAL HOLD: Market in tight consolidation with low IV ({iv * 100:.1f}%). "
                    "Risk-reward unfavorable for theta harvest; capital preserved."
                )

        return SynthesizedTradeDecision(
            strategy=strategy,
            net_conviction=net_conviction,
            confidence_score=confidence,
            target_strikes=target_strikes,
            rationale=rationale,
            risk_status="APPROVED",
            debate_transcript={
                "bull_report": dataclasses.asdict(bull_report),
                "bear_report": dataclasses.asdict(bear_report),
                "rms_override": False,
            },
        )
